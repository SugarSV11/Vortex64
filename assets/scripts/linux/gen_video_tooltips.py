#!/usr/bin/env python3
"""Extracts the tooltip texts of the Windows Glide64/Project64-video
configuration dialogs (TTSetTxt() calls in Source/Project64-video/Config.cpp)
into Source/Project64-video/ConfigTooltips.inc, so the Qt configuration dialog
shows exactly the same help text without retyping it.

usage: Scripts/linux/gen_video_tooltips.py > Source/Project64-video/ConfigTooltips.inc
"""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "Source/Project64-video/Config.cpp").read_text(encoding="utf-8", errors="replace")

def strip_L(s):
    return re.sub(r'\bL"', '"', s)

tips = {}
last = None
# Walk statement by statement (split on ';' outside of string literals).
stmts, cur, in_str, esc = [], [], False, False
for ch in src:
    cur.append(ch)
    if in_str:
        if esc:
            esc = False
        elif ch == "\\":
            esc = True
        elif ch == '"':
            in_str = False
    else:
        if ch == '"':
            in_str = True
        elif ch == ";":
            stmts.append("".join(cur))
            cur = []

for st in stmts:
    m = re.search(r'\btooltip\s*=\s*((?:L?"(?:[^"\\]|\\.)*"\s*)+)\s*;', st)
    if m:
        last = strip_L(m.group(1)).strip()
        continue
    m = re.search(r'\bTTSetTxt\(\s*(\w+)\s*,\s*((?:L?"(?:[^"\\]|\\.)*"\s*)+|tooltip(?:\.c_str\(\))?)\s*\)\s*;', st)
    if m:
        ident, val = m.group(1), m.group(2).strip()
        if val.startswith("tooltip"):
            if last is None:
                continue
            val = last
        else:
            val = strip_L(val)
        tips[ident] = val

print("// Generated by Scripts/linux/gen_video_tooltips.py from Config.cpp - do not edit.")
for ident, val in tips.items():
    print('{"%s", %s},' % (ident, val))
